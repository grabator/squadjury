const dict = { en };
let lang = 'en';

export function setLang(l) {
  if (dict[l]) lang = l;
}

/** Translate a key and fill {placeholders}. */
export function t(key, vars = {}) {
  const s = dict[lang][key] ?? dict.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

